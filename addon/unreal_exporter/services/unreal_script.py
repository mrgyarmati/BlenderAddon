"""Generate the standalone ``import_to_unreal.py`` script (pure, no bpy).

The generated script is the importer core (``unreal_templates/importer_core.py``)
followed by a short entry point that locates the manifest relative to the script.
No absolute paths are embedded, so an export folder can be moved or shared.
"""

from __future__ import annotations

import os

from .. import constants as C

TEMPLATE_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "unreal_templates")
CORE_TEMPLATE = os.path.join(TEMPLATE_DIR, "importer_core.py")

_HEADER = '''# Generated by Unreal Export Bridge {version} for plan {plan_id}.
# Do not edit: re-export from Blender to regenerate.
#
# Run inside Unreal Editor 5.6 or newer (Python Editor Script Plugin enabled):
#   Tools > Execute Python Script... and pick this file, or in the Python console:
#   py "<this folder>/{script_name}"
# Imports every asset listed in {manifest_name} and writes {receipt_name}.
'''

_FOOTER = '''

# ---------------------------------------------------------------- entry point


def _bridge_main():
    try:
        here = os.path.dirname(os.path.abspath(__file__))
    except NameError:
        raise BridgeImportError(
            "Cannot locate the manifest because __file__ is undefined; call "
            "run(r'<export folder>/{manifest_name}') instead."
        )
    return run(os.path.join(here, {manifest_rel!r}))


bridge_receipt = _bridge_main()
'''


def importer_source() -> str:
    with open(CORE_TEMPLATE, "r", encoding="utf-8") as handle:
        return handle.read()


def generate_import_script(plan_id: str, manifest_rel: str = C.MANIFEST_FILENAME) -> str:
    header = _HEADER.format(
        version=C.ADDON_VERSION_STRING,
        plan_id=plan_id[:12],
        script_name=C.IMPORT_SCRIPT_FILENAME,
        manifest_name=C.MANIFEST_FILENAME,
        receipt_name=C.RECEIPT_FILENAME,
    )
    footer = _FOOTER.format(manifest_rel=manifest_rel.replace("\\", "/"), manifest_name=C.MANIFEST_FILENAME)
    return header + importer_source() + footer


def write_import_script(path: str, plan_id: str) -> None:
    text = generate_import_script(plan_id)
    compile(text, path, "exec")  # never write a script that cannot even parse
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
